#!/usr/bin/env node
/**
 * build-graph-data.mjs
 *
 * Reads the four data files in data/ and bundles everything the node-graph
 * viewer needs into a single self-contained script: viewer/data.js
 * (loaded via <script src>, so the viewer also works from file://).
 *
 *   node scripts/build-graph-data.mjs
 *
 * Output shape (window.TAXONOMY):
 *   meta      – version / generatedAt / counts
 *   subjects  – ordered list of subject names (drives the legend)
 *   nodes     – micro-topics (graph nodes)
 *   edges     – prerequisite edges (topic depends on prerequisite)
 *   standards – only the standards actually referenced by topics
 *   curricula – curriculum metadata (slug -> name/country/textIncluded)
 *   clusters  – parent-friendly domain summaries
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'data');
const outDir = join(root, 'viewer');
const outFile = join(outDir, 'data.js');

const read = (name) => readFile(join(dataDir, name), 'utf8').then(JSON.parse);

const [topicsFile, depsFile, standardsFile, clustersFile, manifestFile] = await Promise.all([
  read('topics.json'),
  read('dependencies.json'),
  read('curriculum-standards.json'),
  read('clusters.json'),
  read('manifest.json'),
]);

// ---- nodes ---------------------------------------------------------------
const nodes = topicsFile.topics.map((t) => ({
  id: t.id,
  name: t.name,
  subject: t.subject,
  domain: t.domain,
  type: t.type,
  ageStart: t.ageRangeStart,
  ageEnd: t.ageRangeEnd,
  centrality: Number(t.centrality.toFixed(6)),
  description: t.description,
  evidence: t.evidence,
  assessmentPrompt: t.assessmentPrompt ?? '',
  standards: t.standards ?? [],
}));

const nodeIds = new Set(nodes.map((n) => n.id));

// ---- edges (drop any edge whose endpoints are missing) --------------------
const edges = [];
let dropped = 0;
for (const d of depsFile.dependencies) {
  if (!nodeIds.has(d.topicId) || !nodeIds.has(d.prerequisiteId)) {
    dropped++;
    continue;
  }
  edges.push({
    from: d.prerequisiteId, // prerequisite -> topic (unlock direction)
    to: d.topicId,
    strength: d.strength === 'hard' ? 'hard' : 'soft',
    reason: d.reason ?? '',
  });
}

// ---- curricula metadata ---------------------------------------------------
const curricula = {};
for (const c of standardsFile.curricula) {
  curricula[c.slug] = {
    name: c.name,
    country: c.country,
    version: c.version ?? '',
    textIncluded: !!c.textIncluded,
  };
}

// ---- standards, referenced-only ------------------------------------------
const referenced = new Set(nodes.flatMap((n) => n.standards));
const standards = {};
for (const c of standardsFile.curricula) {
  for (const s of c.topics ?? []) {
    if (!referenced.has(s.key)) continue;
    standards[s.key] = {
      code: s.code,
      curriculum: c.slug,
      textIncluded: !!c.textIncluded,
      title: s.data?.title ?? '',
      description: s.data?.description ?? '',
      keyStage: s.data?.keyStage ?? '',
      subject: s.data?.subject ?? '',
    };
  }
}

// ---- clusters --------------------------------------------------------------
const clusters = clustersFile.clusters.map((c) => ({
  subject: c.subject,
  domain: c.domain,
  ageStart: c.ageRangeStart,
  summary: c.summary,
}));

// ---- bundle ---------------------------------------------------------------
const subjects = [...new Set(nodes.map((n) => n.subject))].sort();

const bundle = {
  meta: {
    dataset: manifestFile.dataset,
    version: manifestFile.taxonomyVersion,
    generatedAt: manifestFile.generatedAt,
    counts: manifestFile.counts,
  },
  subjects,
  nodes,
  edges,
  standards,
  curricula,
  clusters,
};

await mkdir(outDir, { recursive: true });
const js =
  '// Generated by scripts/build-graph-data.mjs — do not edit by hand.\n' +
  '// Source: data/{topics,dependencies,curriculum-standards,clusters,manifest}.json\n' +
  'window.TAXONOMY = ' +
  JSON.stringify(bundle);

await writeFile(outFile, js, 'utf8');

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log(
  `viewer/data.js written: ${nodes.length} nodes, ${edges.length} edges ` +
    `(${dropped} dangling edges dropped), ${Object.keys(standards).length} standards, ` +
    `${clusters.length} clusters — ${kb(Buffer.byteLength(js))}`
);
